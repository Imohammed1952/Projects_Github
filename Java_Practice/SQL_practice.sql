CREATE TABLE EXAMPLE_TABLE {
    ID INT          NOT NULL
    NAME VARCHAR(255) NOT NULL
    AGE INT          NOT NULL
    PRIMARY KEY (ID)
};


CREATE TABLE ANOTHER_TABLE {
    ID INT          NOT NULL
    DATE DATETIME
    CUSTOMER_ID INT REFERENCES EXAMPLE_TABLE(ID)
    PRIMARY KEY (ID)
}

INSERT INTO EXAMPLE_TABLE (ID, NAME, AGE) VALUES (1, 'JOHN DOE', 30);
